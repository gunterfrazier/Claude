#!/usr/bin/env node
/**
 * Builds the bundled Bible texts in assets/bible/<translation>/<book>.txt and the
 * asset index in src/data/bible-assets.ts.
 *
 *   npm run bible:build                       # downloads the sources (needs network access)
 *   npm run bible:build -- --source-dir DIR   # uses DIR/<file>.json downloaded earlier
 *
 * Sources: https://github.com/scrollmapper/bible_databases (JSON format). Every translation
 * bundled here is public domain or CC0, so the full text can ship inside the app.
 *
 * Each output file is JSON: an array of chapters, each an array of verse strings
 * (index 0 = verse 1). Files use a .txt extension so Metro bundles them as assets
 * that are loaded on demand rather than inlined into the JavaScript bundle.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE_URL = "https://raw.githubusercontent.com/scrollmapper/bible_databases/master/formats/json";

/** Order matters: the first translation is the app default. */
const TRANSLATIONS = [
  { id: "BSB", file: "BSB", clean: (t) => t },
  { id: "NHEB", file: "NHEB", clean: (t) => t },
  {
    id: "KJV",
    file: "KJVPCE",
    // Pilcrow paragraph marks; drop-cap capitals at chapter starts ("IN the beginning").
    clean: (t, verse) => {
      let out = t.replace(/¶\s*/g, "");
      // The drop cap can follow a psalm heading ("A Psalm of David. THE Lord").
      if (verse === 1) out = out.replace(/\b([A-Z])([A-Z]+)\b/, (_, a, b) => a + b.toLowerCase());
      return out;
    },
  },
  { id: "ASV", file: "ASV", clean: (t) => t.replace(/\s*\[Selah\]?/g, " Selah").trim() },
];

const args = process.argv.slice(2);
const sourceDir = args.includes("--source-dir") ? path.resolve(args[args.indexOf("--source-dir") + 1]) : null;

async function loadSource(file) {
  if (sourceDir) return JSON.parse(fs.readFileSync(path.join(sourceDir, `${file}.json`), "utf8"));
  const res = await fetch(`${SOURCE_URL}/${file}.json`);
  if (!res.ok) throw new Error(`Download failed for ${file}: HTTP ${res.status}`);
  return res.json();
}

const chapterCounts = [];
const assetLines = [];

for (const t of TRANSLATIONS) {
  const src = await loadSource(t.file);
  if (!Array.isArray(src.books) || src.books.length !== 66) throw new Error(`${t.id}: expected 66 books`);
  const outDir = path.join(root, "assets/bible", t.id);
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });

  let verseCount = 0;
  const requires = [];
  src.books.forEach((book, bookIndex) => {
    const chapters = [...book.chapters]
      .sort((a, b) => a.chapter - b.chapter)
      .map((ch) => {
        const verses = [];
        for (const v of ch.verses) {
          verses[v.verse - 1] = t.clean(String(v.text).trim(), v.verse);
          verseCount++;
        }
        return Array.from(verses, (v) => v ?? "");
      });
    if (t.id === TRANSLATIONS[0].id) chapterCounts.push(chapters.length);
    const name = `${String(bookIndex + 1).padStart(2, "0")}.txt`;
    fs.writeFileSync(path.join(outDir, name), JSON.stringify(chapters));
    requires.push(`require("../../assets/bible/${t.id}/${name}")`);
  });
  assetLines.push(`  ${t.id}: [\n    ${requires.join(",\n    ")},\n  ],`);
  console.log(`${t.id}: ${verseCount} verses`);
}

const index = `// GENERATED by scripts/build-bible.mjs. Do not edit by hand.
/* eslint-disable @typescript-eslint/no-require-imports */

/** Asset module ids for each translation, indexed by book number - 1. */
export const BIBLE_ASSETS = {
${assetLines.join("\n")}
} as const;

/** Chapters per book (Genesis = index 0), from the ${TRANSLATIONS[0].id} text. */
export const CHAPTER_COUNTS: readonly number[] = ${JSON.stringify(chapterCounts)};
`;
fs.writeFileSync(path.join(root, "src/data/bible-assets.ts"), index);
console.log("Wrote src/data/bible-assets.ts");

#!/usr/bin/env node
/**
 * Regenerates src/data/figures.ts from the original BibliaTree web prototype
 * (reference/bibliatree-web.html), so the mobile app and the prototype share one dataset.
 *
 *   npm run data:extract
 *
 * Only the INITIAL_BIBLE_FIGURES array literal is evaluated, in an empty VM context.
 */
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "reference/bibliatree-web.html");
const outPath = path.join(root, "src/data/figures.ts");

// Run-together words in the prototype's text.
const TYPO_FIXES = [
  ["Aworker of the ground", "A worker of the ground"],
  ["And Moseswas content", "And Moses was content"],
  ["aworthy man of the clan", "a worthy man of the clan"],
];

const html = fs.readFileSync(sourcePath, "utf8");
const startMarker = "const INITIAL_BIBLE_FIGURES = ";
const start = html.indexOf(startMarker);
const end = html.indexOf("// APPLICATION STATE & STORAGE INITIALIZATION");
if (start < 0 || end < 0) throw new Error("Could not find INITIAL_BIBLE_FIGURES in the prototype");

let literal = html.slice(start + startMarker.length, end).trim();
literal = literal
  .replace(/\/\/ =+\s*$/, "")
  .trim()
  .replace(/;$/, "");
for (const [from, to] of TYPO_FIXES) {
  if (!literal.includes(from)) throw new Error(`Typo fix no longer applies: ${from}`);
  literal = literal.replace(from, to);
}

const figures = vm.runInNewContext(`(${literal})`, Object.create(null), { timeout: 2000 });
if (!Array.isArray(figures) || figures.length === 0) throw new Error("No figures parsed");

const ids = new Set();
for (const f of figures) {
  if (ids.has(f.id)) throw new Error(`Duplicate figure id: ${f.id}`);
  ids.add(f.id);
}

const dangling = [];
for (const f of figures) {
  for (const rel of ["parents", "spouses", "children", "associates"]) {
    for (const id of f[rel] ?? []) if (!ids.has(id)) dangling.push(`${f.id}.${rel} -> ${id}`);
  }
}

const header = `// GENERATED by scripts/extract-figures.mjs from reference/bibliatree-web.html. Do not edit by hand.
// ${figures.length} figures.${dangling.length ? ` Unresolved references (ignored at runtime): ${dangling.join(", ")}.` : ""}
import type { Figure } from "./types";

export const FIGURES: Figure[] = `;

fs.writeFileSync(outPath, `${header}${JSON.stringify(figures, null, 2)};\n`);
console.log(`Wrote ${figures.length} figures to ${path.relative(root, outPath)}`);
if (dangling.length) console.log(`Unresolved references: ${dangling.join(", ")}`);
